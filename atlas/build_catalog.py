#!/usr/bin/env python3
"""Build the browser data and complete reading copy from the reviewed catalogue."""
import json
from collections import Counter
from pathlib import Path
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parents[1]
LABELS = {
    "exact": "Exact identity / written proof",
    "finite": "Finite-depth observation",
    "reported": "Reported computation",
    "conjectural": "Conjectural direction",
    "exploratory": "Exploratory construction",
    "tooling": "Research tooling",
}


def build():
    data = json.loads((ROOT / "atlas/catalog.json").read_text())
    entries = data["entries"]
    ids = [entry["id"] for entry in entries]
    if len(ids) != len(set(ids)):
        raise ValueError("Atlas entry IDs must be unique")
    for entry in entries:
        for key in ("id", "title", "family", "status", "origin", "summary", "formula", "why", "detail", "next", "sources", "connections"):
            if key not in entry or (key != "connections" and not entry[key]):
                raise ValueError(f"{entry.get('id')}: missing {key}")
        if entry["status"] not in LABELS:
            raise ValueError(f"Unknown evidence level: {entry['status']}")
        if not isinstance(entry["detail"], list):
            raise ValueError("Detail must be a list of paragraphs")
        for related in entry["connections"]:
            if related not in ids or related == entry["id"]:
                raise ValueError(f"Invalid connection: {entry['id']} -> {related}")
        for source in entry["sources"]:
            parsed = urlsplit(source["url"])
            if parsed.scheme != "https" or not parsed.netloc:
                raise ValueError(f"Expected public HTTPS source: {source['url']}")
    payload = json.dumps(data, ensure_ascii=False, indent=2).replace("</", "<\\/")
    (ROOT / "assets/research-atlas-data.js").write_text(
        "/* Generated by atlas/build_catalog.py; edit atlas/catalog.json. */\n"
        "window.ENCAPSULATOR_ATLAS = " + payload + ";\n"
    )
    counts = Counter(entry["status"] for entry in entries)
    lines = [
        "# EncapsulatorP · research atlas", "", f"**Edition: {data['edition']}.**", "",
        "[Open the interactive atlas](https://encapsulatorp.github.io/#atlas)", "",
        data["coverage"], "", data["attribution"], "",
        "## Read the evidence", "",
        "Exact entries contain an identity or a written argument under stated assumptions. "
        "Finite-depth observations concern the displayed construction and cutoff. Reported "
        "computations retain their original provenance and are not described as reruns. "
        "Exploratory constructions and conjectural directions include the next concrete question. "
        "Classical identities are credited as mathematical background; no priority claim follows from inclusion.", "",
        " | ".join(f"{LABELS[k]}: {counts[k]}" for k in LABELS if counts[k]), "",
        "## Navigate", "",
    ]
    lines += [f"- [{entry['title']}](#{entry['id']})" for entry in entries]
    for entry in entries:
        lines += ["", f'<a id="{entry["id"]}"></a>', f"## {entry['title']}", "",
                  f"**{LABELS[entry['status']]} · {entry['family']}**", "",
                  f"*Origin: {entry['origin']}*", "", entry["summary"], "",
                  "```text", entry["formula"], "```", "", f"**Why follow it.** {entry['why']}", ""]
        for paragraph in entry["detail"]:
            lines += [paragraph, ""]
        lines += [f"**Next experiment or question.** {entry['next']}", "", "**Sources**", ""]
        lines += [f"- [{source['label']}]({source['url']})" for source in entry["sources"]]
        if entry["connections"]:
            lines += ["", "**Related:** " + " · ".join(f"[{rid}](#{rid})" for rid in entry["connections"])]
    lines += ["", "---", "", "## Reproduce and maintain", "",
              "`python3 atlas/reproduce.py` checks selected exact arithmetic and 70-digit tower calculations.", "",
              "`python3 atlas/reproduce_experiments.py` recomputes the recovered finite tower examples and selected bridges (mpmath required).", "",
              "`python3 atlas/build_catalog.py` validates and rebuilds this reading copy and the browser data from `atlas/catalog.json`.", "",
              "[Written arguments](mathematical-notes.md) · [Recovered bridges](recovered-bridges.md) · [Recovery provenance](recovery-notes.md)", ""]
    (ROOT / "atlas/README.md").write_text("\n".join(lines))
    from build_html_atlas import build_catalog_html, build_traps
    build_catalog_html()
    build_traps()
    print(json.dumps({"entries": len(entries), "families": len(set(e['family'] for e in entries)), "evidence": counts}, sort_keys=True))


if __name__ == "__main__":
    build()
