#!/usr/bin/env python3
"""Build the shared rail payload and a lightweight, readable evidence route."""
import html
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def build():
    data = json.loads((ROOT / "atlas/stress-tests.json").read_text())
    entries = data["entries"]
    ids = [entry["id"] for entry in entries]
    if len(ids) != len(set(ids)):
        raise ValueError("Duplicate stress-test ID")
    for entry in entries:
        for field in ("id", "title", "claimClass", "obstruction", "formula", "hook", "href", "source"):
            if not entry.get(field):
                raise ValueError(f"Missing {field}: {entry.get('id')}")
        if not entry["source"].startswith("https://"):
            raise ValueError("Sources must use HTTPS")
    payload = json.dumps(data, ensure_ascii=False, indent=2).replace("</", "<\\/")
    (ROOT / "assets/stress-test-data.js").write_text(
        "/* Generated by atlas/build_evidence.py; edit atlas/stress-tests.json. */\n"
        "window.ATLAS_STRESS_TESTS = " + payload + ";\n"
    )
    esc = html.escape
    rows = []
    for entry in entries:
        check = entry.get("checkPath", "lemmas/verify_lemmas.py" if entry["id"] == "mobius-counterexample" else "atlas/verify_stress_tests.py")
        rows.append(
            f'<tr id="{esc(entry["id"])}"><td data-label="Claim &amp; class"><strong>{esc(entry["title"])}</strong>'
            f'<span class="ev-index-claim">{esc(entry["claimClass"])}</span><span class="ev-formula">{esc(entry["formula"])}</span>'
            f'<a href="../{esc(entry["href"])}">Open the entry →</a></td>'
            f'<td data-label="Obstruction / next order">{esc(entry["obstruction"])}</td>'
            f'<td data-label="Verification hook">{esc(entry["hook"])}<span class="ev-index-links">'
            f'<a href="{esc(entry["source"])}">Argument &amp; boundaries ↗</a>'
            f'<a href="https://github.com/EncapsulatorP/EncapsulatorP.github.io/blob/main/{esc(check)}">Runnable check ↗</a>'
            '</span><small>Lean status: formalization pending; no machine-checked proof claimed.</small></td></tr>'
        )
    page = '''<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><meta name="theme-color" content="#f5f2eb"><meta name="description" content="A compact evidence index: exact claims, asymptotics, counterexamples, finite computations and their verification boundaries."><title>Evidence index · EncapsulatorP</title><link rel="icon" href="../assets/logo-encapsulatorp-96.png"><link rel="stylesheet" href="../assets/evidence-board.css"><link rel="stylesheet" href="../assets/atlas-theme.css"><script src="../assets/pq-wordmark.js?v=map-layout-1" defer></script></head>
<body><main class="ev-index"><header class="pq-page-brand"><a data-pq-brand href="../"><img src="../assets/logo-encapsulatorp-96.png" alt="" width="27" height="27">EncapsulatorP</a></header><nav class="ev-index-nav" aria-label="Research navigation"><a href="../#atlas">EncapsulatorP · Atlas</a><a href="../#evidence-start">Evidence board</a><a href="../#paper-table">Shape workbench</a><a href="../recaman/">Recamán</a></nav><h1>A claim.<br>Its boundary.<br>A way to check.</h1><p class="ev-intro">The strongest featured arguments, useful counterexamples and finite experiments in one small reading view. Each keeps its assumptions and a runnable verification hook beside the statement.</p><p class="ev-intro">The shape workbench remains a visual way in. This index provides a separate, direct route to the evidence. A finite check supports inspection; it does not establish an infinite theorem.</p>
<table aria-label="Claims, obstructions and verification hooks"><thead><tr><th scope="col">Claim &amp; class</th><th scope="col">Obstruction / next order</th><th scope="col">Verification hook</th></tr></thead><tbody>'''
    page += "\n".join(rows)
    page += f'''</tbody></table><footer class="ev-standalone-footer"><p>{esc(data["credit"])}</p><p>Classical identities retain their usual mathematical attribution; inclusion makes no priority claim. <a href="../atlas/stress-test-notes.md">Written mathematical notes</a> · <a href="../atlas/stress-tests.json">Source data</a> · <a href="../qa/evidence-order.html">Presentation comparison</a></p></footer></main></body></html>\n'''
    (ROOT / "evidence").mkdir(exist_ok=True)
    (ROOT / "evidence/index.html").write_text(page)
    print(f"Built {len(entries)} evidence entries and the standalone index.")


if __name__ == "__main__":
    build()
