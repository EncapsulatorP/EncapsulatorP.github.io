#!/usr/bin/env python3
"""Build the static Home stylesheet while keeping the original cascade order."""
from pathlib import Path
import re

ASSETS = Path(__file__).resolve().parent
SOURCES = [
    "home-base", "research-atlas", "treasure-rooms", "goldbach-lab",
    "curious-cabinet", "paper-atlas", "visual-first", "evidence-board",
    "recaman-explorer", "interactive-space", "pirates-plan",
    "treasure-entry", "atlas-theme",
]

parts = ["/* Generated by assets/build_home_css.py. Edit the source stylesheets. */"]
parts.append((ASSETS / "atlas-palette.css").read_text().strip())
for name in SOURCES:
    source = (ASSETS / f"{name}.css").read_text().strip()
    if name == "atlas-theme":
        source = re.sub(r'^@import url\("atlas-palette\.css[^"]*"\);\s*', "", source, count=1)
    if re.search(r"^@import\b", source, flags=re.M):
        raise ValueError(f"Unexpected CSS import in {name}")
    for original, shared in (
        ('"IBM Plex Sans"', 'var(--atlas-sans)'),
        ('"Fraunces"', 'var(--atlas-serif)'),
        ('"IBM Plex Mono"', 'ui-monospace'),
    ):
        source = source.replace(original, shared)
    parts.append(f"/* {name}.css */\n{source}")

(ASSETS / "home.css").write_text("\n\n".join(parts) + "\n")
